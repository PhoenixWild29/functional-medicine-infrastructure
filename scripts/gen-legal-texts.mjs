// ============================================================
// Generate src/lib/onboarding/legal-texts.generated.ts
// ============================================================
//
// The onboarding wizard shows legal templates in the browser, and the
// acceptance record stores the SHA-256 of the EXACT text. The source of
// truth is the Markdown under src/content/legal/; this copies it, byte
// for byte (line endings normalised to LF, as git stores them), into a
// TypeScript string the client can import. A test fails if the two ever
// differ, so edit the Markdown and re-run:
//
//   node scripts/gen-legal-texts.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createHash } from 'node:crypto'

const ROOT = process.cwd()
const SOURCES = [
  { name: 'BAA_V0_1_TEXT', file: 'src/content/legal/baa-draft-v0.1.md' },
]

const out = [
  '// GENERATED by scripts/gen-legal-texts.mjs from src/content/legal/*.md. Do not edit by hand.',
  '// The exact text whose SHA-256 an acceptance records (LF line endings).',
  '',
]
for (const s of SOURCES) {
  const text = readFileSync(join(ROOT, s.file), 'utf8').replace(/\r\n/g, '\n')
  const sha = createHash('sha256').update(text, 'utf8').digest('hex')
  out.push(`/** ${s.file} (sha256 ${sha}) */`)
  out.push(`export const ${s.name} = ${JSON.stringify(text)}`)
  out.push('')
  console.log(`${s.file}: sha256 ${sha}`)
}
writeFileSync(join(ROOT, 'src/lib/onboarding/legal-texts.generated.ts'), out.join('\n'))
